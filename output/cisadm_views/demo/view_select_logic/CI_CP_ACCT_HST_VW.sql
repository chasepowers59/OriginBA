-- SELECT logic for CISADM.CI_CP_ACCT_HST_VW
SELECT CP.ACCT_ID
      ,LU.LANGUAGE_CD
      ,CP.COLL_PROC_ID
      ,'          '
      ,CP.CRE_DTTM
      ,LU.FIELD_VALUE
      ,LU.DESCR
      ,TO_CHAR(CP.CRE_DTTM,'YYYY-MM-DD-HH24.MI.SS') ||'.000000'
  FROM CI_COLL_PROC   CP
      ,CI_LOOKUP       LU
   WHERE
   LU.FIELD_NAME = 'ACT_TYPE_FLG'
   AND LU.FIELD_VALUE = 'CP'
   AND CP.COLL_STATUS_FLG = '20'
WITH READ ONLY
 
