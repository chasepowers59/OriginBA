-- SELECT logic for CISADM.W1_PARENT_ORG_VW
WITH R (NODE_ID,PARENT_NODE_ID,IS_ORG) AS
  (SELECT NODE.NODE_ID,
    NODE.PARENT_NODE_ID ,
    (
    CASE
      WHEN NTYP.INST_ASSET_REL_FLG    = 'W1NO'
      AND NTYP.NOT_INST_ASSET_REL_FLG = 'W1NO'
      THEN'Y'
      ELSE 'N'
    END) AS IS_ORG
  FROM W1_NODE NODE,
    W1_NODE PNODE,
    W1_NODE_TYPE NTYP
  WHERE PNODE.NODE_TYPE_CD = NTYP.NODE_TYPE_CD
  AND NODE.PARENT_NODE_ID  = PNODE.NODE_ID
  UNION ALL
  SELECT R.NODE_ID,
    NODE.PARENT_NODE_ID ,
    (
    CASE
      WHEN NTYP.INST_ASSET_REL_FLG    = 'W1NO'
      AND NTYP.NOT_INST_ASSET_REL_FLG = 'W1NO'
      THEN'Y'
      ELSE 'N'
    END) AS IS_ORG
  FROM W1_NODE NODE ,
    W1_NODE PNODE,
    W1_NODE_TYPE NTYP,
    R
  WHERE PNODE.NODE_TYPE_CD = NTYP.NODE_TYPE_CD
  AND NODE.NODE_ID         = R.PARENT_NODE_ID
  AND NODE.PARENT_NODE_ID  = PNODE.NODE_ID
  AND R.IS_ORG             = 'N'
  )
SELECT DISTINCT PARENT_NODE_ID,NODE_ID FROM R WHERE IS_ORG = 'Y'
