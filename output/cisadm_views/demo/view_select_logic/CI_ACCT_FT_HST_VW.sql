-- SELECT logic for CISADM.CI_ACCT_FT_HST_VW
SELECT
  SA.ACCT_ID,
  FT.ARS_DT,
  FT.FT_TYPE_FLG,
  FT.PARENT_ID,
  SUM(FT.CUR_AMT),
  SUM(FT.TOT_AMT),
  FT.CURRENCY_CD
FROM
  CI_FT FT, CI_SA SA
WHERE
  FT.SA_ID=SA.SA_ID AND
  FT.FREEZE_DTTM IS NOT NULL
GROUP BY
 SA.ACCT_ID, FT.ARS_DT, FT.FT_TYPE_FLG, FT.PARENT_ID, FT.CURRENCY_CD
 
