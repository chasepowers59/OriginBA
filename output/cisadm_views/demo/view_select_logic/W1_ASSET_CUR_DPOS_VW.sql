-- SELECT logic for CISADM.W1_ASSET_CUR_DPOS_VW
SELECT A.ASSET_ID, 
A.EFF_DTTM,
       A.ASSET_DPOS_FLG,         
       ' ' AS ATTCH_TO_ASSET_ID,
       ' ' ATTCH_TO_ASSET_DPOS_FLG,
	    A.NODE_ID
FROM W1_ASSET_NODE A
WHERE A.CURR_NODE_ID IS NOT NULL
UNION
SELECT A.ASSET_ID, 
	    A.EFF_DTTM,
       A.ASSET_DPOS_FLG,         
       A.ATTCH_TO_ASSET_ID,
       B.ASSET_DPOS_FLG AS ATTCH_TO_ASSET_DPOS_FLG,
	    B.NODE_ID
FROM W1_ASSET_NODE A,
       W1_ASSET_NODE B
WHERE B.CURR_ASSET_ID = A.CURR_ATTCH_TO_ASSET_ID
 
 
