-- SELECT logic for CISADM.CI_CC_ACCT_HST_VW
SELECT
    AP.ACCT_ID,
    LU.LANGUAGE_CD,
    CC.CC_ID,
    AP.PER_ID,
    CC.CC_DTTM,
    LU.FIELD_VALUE,
    LU.DESCR,
    TO_CHAR(CC.CC_DTTM, 'YYYY-MM-DD-HH24.MI.SS') || '.000000'
FROM
    CI_CC CC,
    CI_ACCT_PER AP,
    CI_LOOKUP LU
WHERE
    AP.PER_ID = CC.PER_ID
    AND LU.FIELD_NAME = 'ACT_TYPE_FLG'
    AND LU.FIELD_VALUE = 'CC'
    AND CC.ACCT_ID IS NULL
UNION
SELECT
    CC.ACCT_ID,
    LU.LANGUAGE_CD,
    CC.CC_ID,
    CC.PER_ID,
    CC.CC_DTTM,
    LU.FIELD_VALUE,
    LU.DESCR,
    TO_CHAR(CC.CC_DTTM, 'YYYY-MM-DD-HH24.MI.SS') || '.000000'
FROM
    CI_CC CC,
    CI_LOOKUP LU
WHERE
    LU.FIELD_NAME = 'ACT_TYPE_FLG'
    AND LU.FIELD_VALUE = 'CC'
    AND CC.ACCT_ID IS NOT NULL

WITH READ ONLY
