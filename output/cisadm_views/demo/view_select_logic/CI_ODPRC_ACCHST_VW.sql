-- SELECT logic for CISADM.CI_ODPRC_ACCHST_VW
SELECT OP.ACCT_ID
      ,LP.LANGUAGE_CD
      ,OP.OD_PROC_ID
      , '          '
      ,OP.CRE_DTTM
      ,LP.FIELD_VALUE
      ,LP.DESCR
      ,TO_CHAR(OP.CRE_DTTM,'YYYY-MM-DD-HH24.MI.SS') ||'.000000'
 FROM CI_OD_PROC OP, CI_LOOKUP LP
 WHERE
       OP.OD_STATUS_FLG = '20'
   AND LP.FIELD_NAME = 'ACT_TYPE_FLG'
      AND LP.FIELD_VALUE = 'OP'
WITH READ ONLY
 
