CREATE OR REPLACE FORCE EDITIONABLE VIEW "CISADM"."C1_SYRQ_PER_NF_VW" ("CRE_DTTM", "F1_SYNC_REQ_ID", "ACCT_ID", "PER_ID") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
  FROM F1_SYNC_REQ SR,
    CI_SA_SP SASP,
    CI_SA SA,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD       = 'SP'
  AND SR.PK_VALUE1            = SASP.SP_ID
  AND SASP.SA_ID              = SA.SA_ID
  AND SA.ACCT_ID              = AP.ACCT_ID
  AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
  AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
  AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
  AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
  UNION
  SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
  FROM F1_SYNC_REQ SR,
    CI_SA SA,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD       = 'SA'
  AND SR.PK_VALUE1            = SA.SA_ID
  AND SA.ACCT_ID              = AP.ACCT_ID
  AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
  AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
  AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
  AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
  UNION
  SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
  FROM F1_SYNC_REQ SR,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD       = 'PERSON'
  AND SR.PK_VALUE1            = AP.PER_ID
  AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
  AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
  AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
  AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
  UNION
  SELECT DISTINCT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    ' ' AS ACCT_ID,
    PN.PER_ID
  FROM F1_SYNC_REQ SR,
    CI_PER_NAME PN,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD       = 'PERSON'
  AND SR.PK_VALUE1            = PN.PER_ID
  AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
  AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
  AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
  AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
  AND NOT EXISTS
    ( SELECT 'X' FROM CI_ACCT_PER AP WHERE AP.PER_ID = PN.PER_ID
    )
  UNION
  SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
  FROM F1_SYNC_REQ SR,
    CI_FA FA,
    CI_SA_SP SASP,
    CI_SA SA,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD       = 'FA'
  AND SR.PK_VALUE1            = FA.FA_ID
  AND FA.SP_ID                = SASP.SP_ID
  AND SASP.SA_ID              = SA.SA_ID
  AND SA.ACCT_ID              = AP.ACCT_ID
  AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
  AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
  AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
  AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
  UNION
  SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
  FROM F1_SYNC_REQ SR,
    CI_BSEG BS,
    CI_SA SA,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD       = 'BILL SEG'
  AND SR.PK_VALUE1            = BS.BSEG_ID
  AND BS.SA_ID                = SA.SA_ID
  AND SA.ACCT_ID              = AP.ACCT_ID
  AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
  AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
  AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
  AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
  UNION
  SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
  FROM F1_SYNC_REQ SR,
    CI_SA_COP SACO,
    CI_SA SA,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD       = 'CONTRACT OPT'
  AND SR.PK_VALUE1            = SACO.CONT_OPT_ID
  AND SACO.SA_ID              = SA.SA_ID
  AND SA.ACCT_ID              = AP.ACCT_ID
  AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
  AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
  AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
  AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
  UNION
  SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
  FROM F1_SYNC_REQ SR,
    CI_COP_EVT COE,
    CI_SA_COP SACO,
    CI_SA SA,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD       = 'COP EVENT'
  AND SR.PK_VALUE1            = COE.CONT_OPT_EVT_ID
  AND COE.CONT_OPT_ID         = SACO.CONT_OPT_ID
  AND SACO.SA_ID              = SA.SA_ID
  AND SA.ACCT_ID              = AP.ACCT_ID
  AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
  AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
  AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
  AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
  UNION
  SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
  FROM F1_SYNC_REQ SR,
    CI_SA_REL SAR,
    CI_SA SA,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD       = 'SA REL'
  AND SR.PK_VALUE1            = SAR.SA_REL_ID
  AND SAR.SA_ID               = SA.SA_ID
  AND SA.ACCT_ID              = AP.ACCT_ID
  AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
  AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
  AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
  AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
  UNION
  SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
  FROM F1_SYNC_REQ SR,
    CI_SA SA,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD       = 'SA REL'
  AND SR.PK_VALUE1            = SA.SA_REL_ID
  AND SA.ACCT_ID              = AP.ACCT_ID
  AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
  AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
  AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
  AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
  UNION
  SELECT SR.CRE_DTTM, 
    SR.F1_SYNC_REQ_ID, 
    AP.ACCT_ID, 
    AP.PER_ID
  FROM F1_SYNC_REQ SR, 
    CI_BILL BILL, 
    CI_BSEG BS, 
    CI_SA SA, 
    CI_ACCT_PER AP, 
    F1_BUS_OBJ_STATUS BOS, 
    F1_BUS_OBJ BO
  WHERE SR.MAINT_OBJ_CD = 'BILL'
    AND SR.PK_VALUE1 = BILL.BILL_ID
    AND BILL.BILL_ID = BS.BILL_ID
    AND BS.SA_ID = SA.SA_ID
    AND SA.ACCT_ID = AP.ACCT_ID
    AND BO.BUS_OBJ_CD = SR.BUS_OBJ_CD
    AND BOS.BUS_OBJ_CD = BO.LIFE_CYCLE_BO_CD
    AND BOS.BO_STATUS_CD = SR.BO_STATUS_CD
    AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
UNION
SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
FROM F1_SYNC_REQ SR,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
WHERE SR.MAINT_OBJ_CD       = 'ACCOUNT'
    AND SR.PK_VALUE1            = AP.ACCT_ID
    AND BO.BUS_OBJ_CD           = SR.BUS_OBJ_CD
    AND BOS.BUS_OBJ_CD          = BO.LIFE_CYCLE_BO_CD
    AND BOS.BO_STATUS_CD        = SR.BO_STATUS_CD
    AND BOS.BO_STATUS_COND_FLG <> 'F1FL'
UNION
SELECT SR.CRE_DTTM,
    SR.F1_SYNC_REQ_ID,
    AP.ACCT_ID,
    AP.PER_ID
FROM F1_SYNC_REQ SR,
    C1_NTF_PREF NT,
    CI_ACCT_PER AP,
    F1_BUS_OBJ_STATUS BOS,
    F1_BUS_OBJ BO
WHERE SR.MAINT_OBJ_CD = 'C1-NTF-PREF'
    AND SR.PK_VALUE1 = NT.NTF_PREF_ID
    AND AP.ACCT_ID = NT.ACCT_ID
    AND BO.BUS_OBJ_CD = SR.BUS_OBJ_CD
    AND BOS.BUS_OBJ_CD = BO.LIFE_CYCLE_BO_CD
    AND BOS.BO_STATUS_CD = SR.BO_STATUS_CD
    AND BOS.BO_STATUS_COND_FLG <> 'F1FL';
