-- SQL*PLUS / SQLCL BIND SAFETY (PREVENTS SP2-0552)
-- If you already set binds in SQL Developer, these defaults are harmless.
VAR P_START_DATE VARCHAR2(10);
VAR P_END_DATE VARCHAR2(10);
BEGIN
    IF :P_START_DATE IS NULL THEN
        :P_START_DATE := '2000-01-01';
    END IF;
    IF :P_END_DATE IS NULL THEN
        :P_END_DATE := '2099-12-31';
    END IF;
END;
