-- =====================================================================
-- 3) COMBINED SUMMARY (CSV-FRIENDLY)
-- WHY: One view of A/B/C/D/E match counts and top candidate path.
-- OUTPUT COLUMNS: PATH, MATCH_COUNT, NOTES
-- =====================================================================
WITH
PARAMS AS (
    SELECT
        NVL(TO_DATE(:P_START_DATE, 'YYYY-MM-DD'), DATE '2026-01-01') AS START_DT,
        NVL(TO_DATE(:P_END_DATE,   'YYYY-MM-DD'), DATE '2026-01-31') AS END_DT
    FROM DUAL
),
A_CNT AS (
    SELECT COUNT(*) AS MATCH_COUNT
    FROM CISADM.D1_USAGE U
    JOIN CISADM.CI_SA S
        ON TO_CHAR(U.USG_EXT_ID) = TO_CHAR(S.SA_ID)
    CROSS JOIN PARAMS P
    WHERE U.USG_EXT_ID IS NOT NULL
      AND U.START_DTTM >= P.START_DT
      AND U.START_DTTM <  P.END_DT + 1
),
B_CNT AS (
    SELECT COUNT(*) AS MATCH_COUNT
    FROM CISADM.D1_USAGE U
    JOIN CISADM.CI_ACCT A
        ON TO_CHAR(U.USG_EXT_ID) = TO_CHAR(A.ACCT_ID)
    CROSS JOIN PARAMS P
    WHERE U.USG_EXT_ID IS NOT NULL
      AND U.START_DTTM >= P.START_DT
      AND U.START_DTTM <  P.END_DT + 1
),
C_CNT AS (
    SELECT COUNT(*) AS MATCH_COUNT
    FROM CISADM.D1_USAGE_SCALAR_DTL D
    JOIN CISADM.CI_SA_SP SAS
        ON TO_CHAR(D.D1_SP_ID) = TO_CHAR(SAS.SP_ID)
    CROSS JOIN PARAMS P
    WHERE D.D1_SP_ID IS NOT NULL
      AND D.START_DTTM >= P.START_DT
      AND D.START_DTTM <  P.END_DT + 1
),
D_CNT AS (
    SELECT COUNT(*) AS MATCH_COUNT
    FROM CISADM.D1_USAGE_SCALAR_DTL D
    JOIN CISADM.D1_SP DSP
        ON TO_CHAR(D.D1_SP_ID) = TO_CHAR(DSP.D1_SP_ID)
JOIN CISADM.CI_SP CSP
    ON TO_CHAR(CSP.SP_ID) = TO_CHAR(DSP.D1_SP_ID)
    JOIN CISADM.CI_SA_SP SAS
        ON TO_CHAR(SAS.SP_ID) = TO_CHAR(CSP.SP_ID)
    JOIN CISADM.CI_SA S
        ON TO_CHAR(S.SA_ID) = TO_CHAR(SAS.SA_ID)
    CROSS JOIN PARAMS P
    WHERE D.D1_SP_ID IS NOT NULL
      AND D.START_DTTM >= P.START_DT
      AND D.START_DTTM <  P.END_DT + 1
),
E_CNT AS (
    SELECT COUNT(*) AS MATCH_COUNT
    FROM ALL_TAB_COLUMNS C
WHERE C.OWNER = 'CISADM'
  AND C.TABLE_NAME = 'D1_USAGE'
  AND (
          (C.COLUMN_NAME = 'SA_ID' OR C.COLUMN_NAME LIKE 'SA\_%' ESCAPE '\' OR C.COLUMN_NAME LIKE '%\_SA\_%' ESCAPE '\')
          OR C.COLUMN_NAME LIKE '%SERVICE%AGREEMENT%'
      )
),
F_CNT AS (
    SELECT COUNT(*) AS MATCH_COUNT
    FROM CISADM.CI_BILL B
    LEFT JOIN CISADM.CI_BILL_CYC_L L
        ON TRIM(L.BILL_CYC_CD) = TRIM(B.BILL_CYC_CD)
       AND L.LANGUAGE_CD IN ('ENG', 'EN')
    CROSS JOIN PARAMS P
    WHERE NVL(B.BILL_DT, B.CRE_DTTM) >= P.START_DT
      AND NVL(B.BILL_DT, B.CRE_DTTM) <  P.END_DT + 1
      AND TRIM(B.BILL_CYC_CD) IS NOT NULL
      AND TRIM(L.DESCR) IS NOT NULL
),
G_CNT AS (
    SELECT COUNT(*) AS MATCH_COUNT
    FROM CISADM.D1_USAGE U
    JOIN CISADM.C1_USAGE CU
        ON TO_CHAR(CU.USAGE_ID) = TO_CHAR(U.D1_USAGE_ID)
    JOIN CISADM.CI_SA S
        ON TO_CHAR(S.SA_ID) = TO_CHAR(CU.SA_ID)
    CROSS JOIN PARAMS P
    WHERE U.D1_USAGE_ID IS NOT NULL
      AND U.START_DTTM >= P.START_DT
      AND U.START_DTTM <  P.END_DT + 1
),
H_CNT AS (
    SELECT COUNT(*) AS MATCH_COUNT
    FROM CISADM.D1_USAGE_SCALAR_DTL D
    JOIN CISADM.D1_SP_USG_SNAP_DL SN
        ON TO_CHAR(SN.D1_SP_ID) = TO_CHAR(D.D1_SP_ID)
    JOIN CISADM.CI_SA S
        ON TO_CHAR(S.SA_ID) = TO_CHAR(SN.CIS_EXT_SA_ID)
    CROSS JOIN PARAMS P
    WHERE D.D1_SP_ID IS NOT NULL
      AND D.START_DTTM >= P.START_DT
      AND D.START_DTTM <  P.END_DT + 1
),
I_CNT AS (
    SELECT COUNT(*) AS MATCH_COUNT
    FROM CISADM.D1_USAGE U
    JOIN CISADM.C1_BI_BILLED_USAGE_VW V
        ON TO_CHAR(V.SA_ID) = TO_CHAR(U.USG_EXT_ID)
    CROSS JOIN PARAMS P
    WHERE U.USG_EXT_ID IS NOT NULL
      AND U.START_DTTM >= P.START_DT
      AND U.START_DTTM <  P.END_DT + 1
),
PATH_COUNTS AS (
    SELECT 'A_USG_EXT_ID_TO_SA_ID' AS PATH, (SELECT MATCH_COUNT FROM A_CNT) AS MATCH_COUNT,
           'D1_USAGE.USG_EXT_ID = CI_SA.SA_ID' AS NOTES
    FROM DUAL
    UNION ALL
    SELECT 'B_USG_EXT_ID_TO_ACCT_ID' AS PATH, (SELECT MATCH_COUNT FROM B_CNT) AS MATCH_COUNT,
           'D1_USAGE.USG_EXT_ID = CI_ACCT.ACCT_ID (ACCT_NO CHECK IS OPTIONAL BLOCK)' AS NOTES
    FROM DUAL
    UNION ALL
    SELECT 'C_DTL_D1_SP_ID_TO_CI_SA_SP' AS PATH, (SELECT MATCH_COUNT FROM C_CNT) AS MATCH_COUNT,
           'D1_USAGE_SCALAR_DTL.D1_SP_ID = CI_SA_SP.SP_ID' AS NOTES
    FROM DUAL
    UNION ALL
    SELECT 'D_DTL_VIA_D1_SP_CI_SP_CI_SA_SP' AS PATH, (SELECT MATCH_COUNT FROM D_CNT) AS MATCH_COUNT,
           'D1_USAGE_SCALAR_DTL -> D1_SP -> CI_SP -> CI_SA_SP -> CI_SA' AS NOTES
    FROM DUAL
    UNION ALL
    SELECT 'E_D1_USAGE_DIRECT_SA_POINTER_COLS' AS PATH, (SELECT MATCH_COUNT FROM E_CNT) AS MATCH_COUNT,
           'COUNT OF SA-POINTER-LIKE COLUMNS IN D1_USAGE METADATA' AS NOTES
    FROM DUAL
    UNION ALL
    SELECT 'F_BILL_CYCLE_CODE_WITH_DESCRIPTION' AS PATH, (SELECT MATCH_COUNT FROM F_CNT) AS MATCH_COUNT,
           'CI_BILL.BILL_CYC_CD SUCCESSFULLY MAPS TO CI_BILL_CYC_L.DESCR' AS NOTES
    FROM DUAL
    UNION ALL
    SELECT 'G_D1_USAGE_TO_C1_USAGE_TO_SA' AS PATH, (SELECT MATCH_COUNT FROM G_CNT) AS MATCH_COUNT,
           'D1_USAGE.D1_USAGE_ID -> C1_USAGE.USAGE_ID -> C1_USAGE.SA_ID -> CI_SA.SA_ID' AS NOTES
    FROM DUAL
    UNION ALL
    SELECT 'H_DTL_TO_SP_USG_SNAP_TO_SA' AS PATH, (SELECT MATCH_COUNT FROM H_CNT) AS MATCH_COUNT,
           'D1_USAGE_SCALAR_DTL.D1_SP_ID -> D1_SP_USG_SNAP_DL.CIS_EXT_SA_ID -> CI_SA.SA_ID' AS NOTES
    FROM DUAL
    UNION ALL
    SELECT 'I_USG_EXT_TO_BILLED_USAGE_VW_SA' AS PATH, (SELECT MATCH_COUNT FROM I_CNT) AS MATCH_COUNT,
           'D1_USAGE.USG_EXT_ID -> C1_BI_BILLED_USAGE_VW.SA_ID' AS NOTES
    FROM DUAL
)
SELECT
    PC.PATH,
    PC.MATCH_COUNT,
    CASE
        WHEN PC.MATCH_COUNT = MAX(PC.MATCH_COUNT) OVER () AND PC.MATCH_COUNT > 0
            THEN PC.NOTES || ' | TOP_MATCH_PATH'
        WHEN PC.MATCH_COUNT = 0
            THEN PC.NOTES || ' | NO_MATCH_IN_WINDOW'
        ELSE PC.NOTES
    END AS NOTES
FROM PATH_COUNTS PC
ORDER BY PC.MATCH_COUNT DESC, PC.PATH;

