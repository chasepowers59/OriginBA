       COUNT(*) AS expected_columns,
       SUM(CASE WHEN c.column_name IS NOT NULL THEN 1 ELSE 0 END) AS present_columns,
       SUM(CASE WHEN c.column_name IS NULL THEN 1 ELSE 0 END) AS missing_columns
FROM expected e
LEFT JOIN all_tab_columns c
  ON c.owner = 'CISADM'
 AND c.table_name = e.table_name
 AND c.column_name = e.column_name
GROUP BY e.table_name
ORDER BY e.table_name;

