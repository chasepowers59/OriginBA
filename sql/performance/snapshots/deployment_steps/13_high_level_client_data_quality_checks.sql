       SUM(CASE WHEN ft_id IS NULL THEN 1 ELSE 0 END) AS null_rows,
       ROUND(SUM(CASE WHEN ft_id IS NULL THEN 1 ELSE 0 END) * 100 / NULLIF(COUNT(*), 0), 4) AS null_pct
