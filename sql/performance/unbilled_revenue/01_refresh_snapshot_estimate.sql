-- Purpose:
--   Refresh one AS_OF_DT partition worth of unbilled revenue estimates.
--
-- Bind parameters:
--   :P_AS_OF_DATE      DATE   default SYSDATE
--   :P_LOOKBACK_DAYS   NUMBER default 120
--   :P_SA_STATUS_FLG   CHAR   default '20' (active SA)
--
-- Performance design:
--   - Drives usage extraction from SA-scoped, last-billed windows.
--   - Uses indexed keys where available:
--       C1_USAGE.SA_ID, C1_USAGE.USAGE_ID, D1_USAGE.USG_EXT_ID, D1_USAGE_SCALAR_DTL.D1_USAGE_ID
--   - Keeps Jasper fast by precomputing and persisting results.

DELETE FROM CISADM.C1_BI_UNBILLED_REV_SNAP
 WHERE AS_OF_DT = TRUNC(NVL(:P_AS_OF_DATE, SYSDATE));

INSERT /*+ APPEND */ INTO CISADM.C1_BI_UNBILLED_REV_SNAP (
  AS_OF_DT,
  ACCT_ID,
  SA_ID,
  CIS_DIVISION,
  SA_TYPE_CD,
  SA_TYPE_DESCR,
  BILL_CYC_CD,
  BILL_CYC_DESCR,
  CUST_CL_CD,
  CUST_CLASS_DESCR,
  COLL_CL_CD,
  COLL_CLASS_DESCR,
  RATE_SCHEDULE_CD,
  RATE_SCHEDULE_DESCR,
  LAST_BSEG_END_DT,
  LAST_BILL_ACCOUNTING_DT,
  UNBILLED_DAYS,
  UNBILLED_USAGE_QTY,
  EST_USAGE_AMT,
  EST_OTHER_AMT,
  EST_TAX_RATE,
  EST_TAX_AMT,
  EST_TOTAL_AMT,
  CALC_METHOD_CD,
  LOAD_DTTM
)
WITH
PARAMS AS (
  SELECT
    TRUNC(NVL(:P_AS_OF_DATE, SYSDATE)) AS AS_OF_DT,
    NVL(:P_LOOKBACK_DAYS, 120) AS LOOKBACK_DAYS,
    NVL(:P_SA_STATUS_FLG, '20') AS SA_STATUS_FLG
  FROM DUAL
),
SA_BASE AS (
  SELECT
    S.SA_ID,
    S.ACCT_ID,
    S.CIS_DIVISION,
    S.SA_TYPE_CD
  FROM CISADM.CI_SA S
  JOIN PARAMS P
    ON 1 = 1
  WHERE S.SA_STATUS_FLG = P.SA_STATUS_FLG
),
LAST_BILLED AS (
  SELECT
    B.SA_ID,
    MAX(B.BSEG_END_DT) AS LAST_BSEG_END_DT,
    MAX(B.ACCOUNTING_DT) AS LAST_BILL_ACCOUNTING_DT,
    MAX(B.RS_CD) KEEP (DENSE_RANK LAST ORDER BY B.ACCOUNTING_DT, B.BSEG_END_DT) AS LAST_RS_CD
  FROM CISADM.C1_BI_BILLED_USAGE_VW B
  JOIN SA_BASE S
    ON S.SA_ID = B.SA_ID
  GROUP BY
    B.SA_ID
),
SA_WINDOW AS (
  SELECT
    P.AS_OF_DT,
    S.SA_ID,
    S.ACCT_ID,
    S.CIS_DIVISION,
    S.SA_TYPE_CD,
    L.LAST_RS_CD,
    L.LAST_BSEG_END_DT,
    L.LAST_BILL_ACCOUNTING_DT,
    GREATEST(0, TRUNC(P.AS_OF_DT) - TRUNC(L.LAST_BSEG_END_DT)) AS UNBILLED_DAYS
  FROM SA_BASE S
  JOIN LAST_BILLED L
    ON L.SA_ID = S.SA_ID
  JOIN PARAMS P
    ON 1 = 1
  WHERE L.LAST_BSEG_END_DT < P.AS_OF_DT + 1
),
UNBILLED_QTY AS (
  SELECT
    W.SA_ID,
    NVL(U.D1_FINAL_UOM_CD, U.D1_UOM_CD) AS UOM_CD,
    NVL(U.D1_FINAL_TOU_CD, U.D1_TOU_CD) AS TOU_CD,
    NVL(U.D1_FINAL_SQI_CD, U.D1_SQI_CD) AS SQI_CD,
    SUM(NVL(U.FINAL_QUANTITY, U.QUANTITY)) AS UNBILLED_QTY
  FROM SA_WINDOW W
  JOIN CISADM.C1_USAGE CU
    ON CU.SA_ID = W.SA_ID
  JOIN CISADM.D1_USAGE DU
    ON DU.USG_EXT_ID = CU.USAGE_ID
  JOIN CISADM.D1_USAGE_SCALAR_DTL U
    ON U.D1_USAGE_ID = DU.D1_USAGE_ID
  WHERE NVL(DU.USED_ON_BILL_FLG, 'N') <> 'Y'
    AND CU.BSEG_ID IS NULL
    AND NVL(CU.END_DTTM, DU.END_DTTM) > W.LAST_BSEG_END_DT
    AND NVL(CU.END_DTTM, DU.END_DTTM) <= W.AS_OF_DT + 1
  GROUP BY
    W.SA_ID,
    NVL(U.D1_FINAL_UOM_CD, U.D1_UOM_CD),
    NVL(U.D1_FINAL_TOU_CD, U.D1_TOU_CD),
    NVL(U.D1_FINAL_SQI_CD, U.D1_SQI_CD)
),
USAGE_UNIT_RATE AS (
  SELECT
    B.SA_ID,
    B.UOM_CD,
    B.TOU_CD,
    B.SQI_CD,
    CASE
      WHEN SUM(NVL(B.BILL_SQ, 0)) = 0 THEN 0
      ELSE SUM(NVL(B.BILLED_AMT, 0)) / SUM(NVL(B.BILL_SQ, 0))
    END AS UNIT_RATE
  FROM CISADM.C1_BI_BILLED_USAGE_VW B
  JOIN SA_WINDOW W
    ON W.SA_ID = B.SA_ID
  JOIN PARAMS P
    ON 1 = 1
  WHERE B.ACCOUNTING_DT >= P.AS_OF_DT - P.LOOKBACK_DAYS
    AND B.ACCOUNTING_DT <  P.AS_OF_DT + 1
    AND NVL(B.BILL_SQ, 0) <> 0
  GROUP BY
    B.SA_ID,
    B.UOM_CD,
    B.TOU_CD,
    B.SQI_CD
),
USAGE_EST AS (
  SELECT
    Q.SA_ID,
    SUM(Q.UNBILLED_QTY) AS UNBILLED_USAGE_QTY,
    SUM(Q.UNBILLED_QTY * NVL(R.UNIT_RATE, 0)) AS EST_USAGE_AMT
  FROM UNBILLED_QTY Q
  LEFT JOIN USAGE_UNIT_RATE R
    ON R.SA_ID = Q.SA_ID
   AND R.UOM_CD = Q.UOM_CD
   AND R.TOU_CD = Q.TOU_CD
   AND R.SQI_CD = Q.SQI_CD
  GROUP BY
    Q.SA_ID
),
FT_HIST AS (
  SELECT
    F.SA_ID,
    SUM(NVL(F.FT_OTHER_AMT, 0)) AS OTHER_AMT_HIST,
    SUM(NVL(F.FT_GL_TAX_AMT, 0)) AS TAX_AMT_HIST,
    SUM(ABS(NVL(F.FT_GL_REV_AMT, 0))) AS REV_ABS_HIST,
    MIN(TRUNC(F.ACCOUNTING_DT)) AS FIRST_HIST_DT
  FROM CISADM.C1_BI_FT_VW F
  JOIN SA_WINDOW W
    ON W.SA_ID = F.SA_ID
  JOIN PARAMS P
    ON 1 = 1
  WHERE F.ACCOUNTING_DT >= P.AS_OF_DT - P.LOOKBACK_DAYS
    AND F.ACCOUNTING_DT <  P.AS_OF_DT + 1
  GROUP BY
    F.SA_ID
),
OTHER_TAX_EST AS (
  SELECT
    W.SA_ID,
    CASE
      WHEN H.FIRST_HIST_DT IS NULL THEN 0
      ELSE (NVL(H.OTHER_AMT_HIST, 0) / GREATEST(1, W.AS_OF_DT - H.FIRST_HIST_DT + 1)) * W.UNBILLED_DAYS
    END AS EST_OTHER_AMT,
    CASE
      WHEN NVL(H.REV_ABS_HIST, 0) = 0 THEN 0
      ELSE NVL(H.TAX_AMT_HIST, 0) / H.REV_ABS_HIST
    END AS EST_TAX_RATE
  FROM SA_WINDOW W
  LEFT JOIN FT_HIST H
    ON H.SA_ID = W.SA_ID
),
DIM_ENRICHED AS (
  SELECT
    W.AS_OF_DT,
    W.ACCT_ID,
    W.SA_ID,
    W.CIS_DIVISION,
    W.SA_TYPE_CD,
    STL.DESCR AS SA_TYPE_DESCR,
    A.BILL_CYC_CD,
    BCL.DESCR AS BILL_CYC_DESCR,
    A.CUST_CL_CD,
    CCL.DESCR AS CUST_CLASS_DESCR,
    A.COLL_CL_CD,
    COLL.DESCR AS COLL_CLASS_DESCR,
    W.LAST_RS_CD AS RATE_SCHEDULE_CD,
    RSL.DESCR AS RATE_SCHEDULE_DESCR,
    W.LAST_BSEG_END_DT,
    W.LAST_BILL_ACCOUNTING_DT,
    W.UNBILLED_DAYS
  FROM SA_WINDOW W
  LEFT JOIN CISADM.CI_ACCT A
    ON A.ACCT_ID = W.ACCT_ID
  LEFT JOIN CISADM.CI_BILL_CYC_L BCL
    ON BCL.BILL_CYC_CD = A.BILL_CYC_CD
   AND BCL.LANGUAGE_CD = 'ENG'
  LEFT JOIN CISADM.CI_CUST_CL_L CCL
    ON CCL.CUST_CL_CD = A.CUST_CL_CD
   AND CCL.LANGUAGE_CD = 'ENG'
  LEFT JOIN CISADM.CI_COLL_CL_L COLL
    ON COLL.COLL_CL_CD = A.COLL_CL_CD
   AND COLL.LANGUAGE_CD = 'ENG'
  LEFT JOIN CISADM.CI_SA_TYPE_L STL
    ON STL.CIS_DIVISION = W.CIS_DIVISION
   AND STL.SA_TYPE_CD = W.SA_TYPE_CD
   AND STL.LANGUAGE_CD = 'ENG'
  LEFT JOIN CISADM.CI_RS_L RSL
    ON RSL.RS_CD = W.LAST_RS_CD
   AND RSL.LANGUAGE_CD = 'ENG'
)
SELECT
  D.AS_OF_DT,
  D.ACCT_ID,
  D.SA_ID,
  D.CIS_DIVISION,
  D.SA_TYPE_CD,
  D.SA_TYPE_DESCR,
  D.BILL_CYC_CD,
  D.BILL_CYC_DESCR,
  D.CUST_CL_CD,
  D.CUST_CLASS_DESCR,
  D.COLL_CL_CD,
  D.COLL_CLASS_DESCR,
  D.RATE_SCHEDULE_CD,
  D.RATE_SCHEDULE_DESCR,
  D.LAST_BSEG_END_DT,
  D.LAST_BILL_ACCOUNTING_DT,
  D.UNBILLED_DAYS,
  NVL(U.UNBILLED_USAGE_QTY, 0) AS UNBILLED_USAGE_QTY,
  NVL(U.EST_USAGE_AMT, 0) AS EST_USAGE_AMT,
  NVL(O.EST_OTHER_AMT, 0) AS EST_OTHER_AMT,
  NVL(O.EST_TAX_RATE, 0) AS EST_TAX_RATE,
  (NVL(U.EST_USAGE_AMT, 0) + NVL(O.EST_OTHER_AMT, 0)) * NVL(O.EST_TAX_RATE, 0) AS EST_TAX_AMT,
  NVL(U.EST_USAGE_AMT, 0)
    + NVL(O.EST_OTHER_AMT, 0)
    + ((NVL(U.EST_USAGE_AMT, 0) + NVL(O.EST_OTHER_AMT, 0)) * NVL(O.EST_TAX_RATE, 0)) AS EST_TOTAL_AMT,
  'HIST_RATE_PLUS_FT_OTHER_TAX_RATIO' AS CALC_METHOD_CD,
  SYSDATE AS LOAD_DTTM
FROM DIM_ENRICHED D
LEFT JOIN USAGE_EST U
  ON U.SA_ID = D.SA_ID
LEFT JOIN OTHER_TAX_EST O
  ON O.SA_ID = D.SA_ID;

COMMIT;
