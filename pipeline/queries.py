# Revenue Leakage: Canceled SAs that still have outstanding (frozen) arrears — "ghost" debt; prompt write-off or final bill.
QUERY_REVENUE_LEAKAGE_CANCELED_SA = """
SELECT
    SA.ACCT_ID,
    SA.SA_ID,
    SUM(FT.CUR_AMT) AS TOTAL_UNRESOLVED_AMT
FROM CISADM.CI_SA SA
JOIN CISADM.CI_FT FT ON FT.SA_ID = SA.SA_ID
WHERE NULLIF(TRIM(SA.SA_STATUS_FLG), '') = '70'
  AND FT.FREEZE_SW = 'Y'
  AND FT.ARS_DT IS NOT NULL
  AND FT.NOT_IN_ARS_SW = 'N'
  AND FT.FT_TYPE_FLG NOT IN ('PS', 'PX')
GROUP BY SA.ACCT_ID, SA.SA_ID
HAVING SUM(FT.CUR_AMT) > 0
"""

# Liquidity Risk (A): Pending payments (PAY_STATUS_FLG = 'P') — not yet finalized; >48h = Suspense Alert.
QUERY_LIQUIDITY_RISK_PENDING_PAYMENTS = """
SELECT
    PE.PAY_EVENT_ID,
    P.ACCT_ID,
    NVL(P.PAY_AMT, 0) AS PAY_AMT,
    TRUNC(SYSDATE) - TRUNC(PE.CRE_DTTM) AS DAYS_SINCE_CRE
FROM CISADM.CI_PAY_EVENT PE
JOIN CISADM.CI_PAY P ON P.PAY_EVENT_ID = PE.PAY_EVENT_ID
WHERE NULLIF(TRIM(P.PAY_STATUS_FLG), '') = 'P'
  AND PE.CRE_DTTM >= TRUNC(SYSDATE) - 14
"""

# Liquidity Risk (B): Unfrozen payment transactions (CI_FT) — not yet hit GL; >48h = batch/drawer risk.
QUERY_LIQUIDITY_RISK_UNFROZEN_FT = """
SELECT
    FT.FT_ID,
    FT.SA_ID,
    NVL(FT.CUR_AMT, 0) AS CUR_AMT,
    TRUNC(SYSDATE) - TRUNC(FT.CRE_DTTM) AS DAYS_SINCE_CRE
FROM CISADM.CI_FT FT
WHERE FT.FT_TYPE_FLG IN ('PS', 'PX')
  AND FT.FREEZE_SW = 'N'
  AND FT.CRE_DTTM >= TRUNC(SYSDATE) - 14
"""

# Stale Pending SA: New Services still Pending with START_DT in the past — service delay; check F1_TSK.
QUERY_STALE_PENDING_SA = """
SELECT SA_ID, ACCT_ID, START_DT, CRE_DTTM
FROM CISADM.CI_SA
WHERE NULLIF(TRIM(SA_STATUS_FLG), '') = '10'
  AND START_DT IS NOT NULL
  AND TRUNC(START_DT) < TRUNC(SYSDATE)
"""

