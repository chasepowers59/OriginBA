QUERY_DUPLICATE_PAYMENT = """
SELECT b.ACCT_NBR,
       b.ACCT_PAYMENTS_TODAY,
       b.ACCT_PAYMENTS_YESTERDAY,
       'Potential Duplicate Payment' AS ANOMALY_TYPE
FROM (
    SELECT a.ACCT_ID AS ACCT_NBR,
            (SELECT NVL(SUM(ft2.CUR_AMT),0)
             FROM CISADM.CI_FT ft2
             JOIN CISADM.CI_SA sa2 ON sa2.SA_ID = ft2.SA_ID AND NULLIF(TRIM(sa2.SA_STATUS_FLG), '') = '20'
             WHERE sa2.ACCT_ID = a.ACCT_ID
                   AND ft2.REDUNDANT_SW = 'N'
                   AND ft2.FREEZE_SW = 'Y'
                   AND ft2.FT_TYPE_FLG IN ('PS', 'PX')
                   AND TRUNC(ft2.CRE_DTTM) = TRUNC(SYSDATE)
            ) AS ACCT_PAYMENTS_TODAY,
            (SELECT NVL(SUM(ft2.CUR_AMT),0)
             FROM CISADM.CI_FT ft2
             JOIN CISADM.CI_SA sa2 ON sa2.SA_ID = ft2.SA_ID AND NULLIF(TRIM(sa2.SA_STATUS_FLG), '') = '20'
             WHERE sa2.ACCT_ID = a.ACCT_ID
                   AND ft2.REDUNDANT_SW = 'N'
                   AND ft2.FREEZE_SW = 'Y'
                   AND ft2.FT_TYPE_FLG IN ('PS', 'PX')
                   AND TRUNC(ft2.CRE_DTTM) = TRUNC(SYSDATE) - 1
            ) AS ACCT_PAYMENTS_YESTERDAY
    FROM CISADM.CI_ACCT a
) b
WHERE b.ACCT_PAYMENTS_TODAY = b.ACCT_PAYMENTS_YESTERDAY
  AND b.ACCT_PAYMENTS_TODAY <> 0
"""

QUERY_BANKRUPTCY_MONITOR = """
SELECT DISTINCT
    acct.acct_id,
    pym.ars_dt,
    pym.pym_amt
FROM CISADM.ci_acct acct
INNER JOIN CISADM.ci_acct_alert alert ON acct.acct_id = alert.acct_id
    AND alert.alert_type_cd = 'BNKRTPCY'
    AND SYSDATE BETWEEN alert.start_dt AND alert.end_dt
INNER JOIN (
    SELECT sa.acct_id, ft.ars_dt, NVL(SUM(ft.cur_amt),0) AS pym_amt
    FROM CISADM.ci_ft ft
    JOIN CISADM.ci_sa sa ON sa.sa_id = ft.sa_id AND NULLIF(TRIM(sa.SA_STATUS_FLG), '') = '20'
    WHERE ft.ft_type_flg = 'PS' AND ft.freeze_sw = 'Y'
    GROUP BY sa.acct_id, ft.ars_dt
) pym ON acct.acct_id = pym.acct_id
WHERE pym.ars_dt BETWEEN SYSDATE - 60 AND SYSDATE
"""

